package com.nepdon.wire.decode.body;

import java.util.HashMap;

/**
 * Wire layouts for {@value #COUNT} {@code (cmd, direction)} pairs — the shape of
 * every message body the client can send or receive, as a compact program of
 * {@code FastBinaryReader} operations.
 *
 * <h3>The programs</h3>
 * <pre>
 *   U   LEB128 varint, unsigned
 *   Z   LEB128 varint, zigzag-decoded signed
 *   B   ONE RAW BYTE            (ReadByte / ReadBoolean)
 *   F   LEB128 varint whose 32 bits ARE the float32
 *   S   [zigzag varint byte length][UTF-8]
 *   ( ) List&lt;T&gt;: a zigzag varint count, then the enclosed program that many times
 * </pre>
 *
 * <p><b>{@code B} is the whole point of this table.</b> {@code byte} and
 * {@code bool} are one RAW byte while {@code ushort} is a varint, so a naive
 * varint walk desyncs on any raw byte &ge; 0x80 — which is exactly what the
 * leading per-record entity id in 2001/2012 is. See
 * {@code docs/IL2CPP_FINDINGS.md} §3.</p>
 *
 * <h3>Keyed on (cmd, direction) — never on cmd alone</h3>
 * <p>Messages are bidirectional with <b>different classes per direction</b>:
 * Cmd 106 is an 8-field struct inbound and a 22-field struct outbound. A
 * single-layout decoder is wrong in one direction by construction.</p>
 *
 * <h3>Provenance</h3>
 * <p>Generated by joining {@code tools/il2cpp/ff_inbound_registry.tsv} (1384
 * ids → inbound class) and {@code ff_outbound_registry.txt} (461 send sites)
 * against the Il2CppDumper <b>structure</b> — declared field order and declared
 * types only. Declared order is wire order, verified on 11 independent classes
 * across two builds, and re-verified here: all 288 classes of the committed
 * {@code ff_outbound_classes.json} reproduce field-for-field. <b>No RVA from
 * that dump is used anywhere</b> — it is a different build (see
 * {@code IL2CPP_FINDINGS.md} §0, Trap 2). The full artifact, with class names,
 * field paths and per-field provenance, is
 * {@code tools/il2cpp/ff_wire_layouts.json}.</p>
 *
 * <h3>Why a packed string and not a map literal</h3>
 * <p>Same reason as {@link CmdCatalogue}: ~1600 entries as code would put the
 * {@code <clinit>} against the JVM's 64 KB method limit. String constants live
 * in the constant pool and are parsed once, lazily, on first use.</p>
 *
 * <p><b>Generated file — do not hand-edit.</b></p>
 */
public final class BodyDecoderTable {

    /** Wire code: LEB128 varint, unsigned. */
    public static final char OP_UINT = 'U';
    /** Wire code: LEB128 varint, zigzag-decoded. */
    public static final char OP_ZIGZAG = 'Z';
    /** Wire code: one RAW byte. */
    public static final char OP_BYTE = 'B';
    /** Wire code: LEB128 varint whose bits are a float32. */
    public static final char OP_FLOAT = 'F';
    /** Wire code: length-prefixed UTF-8 string. */
    public static final char OP_STRING = 'S';
    /** Wire code: start of a {@code List<T>} (zigzag count, then the body). */
    public static final char OP_LIST_BEGIN = '(';
    /** Wire code: end of a {@code List<T>}. */
    public static final char OP_LIST_END = ')';

    /** Number of {@code (cmd, direction)} pairs with a layout. */
    public static final int COUNT = 1604;

    private BodyDecoderTable() { }

    /** Map key for a command in one direction. Direction is the high bit. */
    private static int key(int cmd, boolean outbound) {
        return outbound ? (cmd | 0x40000) : cmd;
    }

    // Wire layouts (Bucket-B) provided per variant by BodyDecoderTableData
    // — full in debug, EMPTY in release (docs/SECURITY_MODEL.md).
    // GENERATED-fed by tools/offload_body_layouts.py.

    // Packed "<cmd:slot=name,slot=name", '|'-separated. Only named slots appear.

    private static volatile HashMap<Integer, String> programs;
    private static volatile HashMap<Integer, String[]> fieldNames;

    private static void ensure() {
        if (programs != null) return;
        synchronized (BodyDecoderTable.class) {
            if (programs != null) return;
            HashMap<Integer, String> p = new HashMap<Integer, String>(2048);
            for (int c = 0; c < BodyDecoderTableData.PACKED_PROGRAMS.length; c++) {
                parseProgramChunk(BodyDecoderTableData.PACKED_PROGRAMS[c], p);
            }
            HashMap<Integer, String[]> n = new HashMap<Integer, String[]>(1024);
            for (int c = 0; c < BodyDecoderTableData.PACKED_NAMES.length; c++) {
                parseNameChunk(BodyDecoderTableData.PACKED_NAMES[c], p, n);
            }
            fieldNames = n;
            programs = p;   // published last: ensure() keys off this
        }
    }

    private static void parseProgramChunk(String chunk, HashMap<Integer, String> into) {
        int i = 0;
        int len = chunk.length();
        while (i < len) {
            int end = chunk.indexOf('|', i);
            if (end < 0) end = len;
            int colon = chunk.indexOf(':', i);
            if (colon > i && colon < end) {
                boolean out = chunk.charAt(i) == '>';
                int cmd = 0;
                for (int k = i + 1; k < colon; k++) cmd = cmd * 10 + (chunk.charAt(k) - '0');
                into.put(key(cmd, out), chunk.substring(colon + 1, end));
            }
            i = end + 1;
        }
    }

    private static void parseNameChunk(String chunk, HashMap<Integer, String> progs,
                                       HashMap<Integer, String[]> into) {
        int i = 0;
        int len = chunk.length();
        while (i < len) {
            int end = chunk.indexOf('|', i);
            if (end < 0) end = len;
            int colon = chunk.indexOf(':', i);
            if (colon > i && colon < end) {
                boolean out = chunk.charAt(i) == '>';
                int cmd = 0;
                for (int k = i + 1; k < colon; k++) cmd = cmd * 10 + (chunk.charAt(k) - '0');
                int k = key(cmd, out);
                String prog = progs.get(k);
                if (prog != null) {
                    String[] arr = new String[slotCount(prog)];
                    int j = colon + 1;
                    while (j < end) {
                        int comma = chunk.indexOf(',', j);
                        if (comma < 0 || comma > end) comma = end;
                        int eq = chunk.indexOf('=', j);
                        if (eq > j && eq < comma) {
                            int slot = 0;
                            for (int q = j; q < eq; q++) slot = slot * 10 + (chunk.charAt(q) - '0');
                            if (slot >= 0 && slot < arr.length) {
                                arr[slot] = chunk.substring(eq + 1, comma);
                            }
                        }
                        j = comma + 1;
                    }
                    into.put(k, arr);
                }
            }
            i = end + 1;
        }
    }

    /** Number of value-producing slots in a program (parentheses produce none). */
    public static int slotCount(String prog) {
        int n = 0;
        for (int i = 0; i < prog.length(); i++) {
            char c = prog.charAt(i);
            if (c != OP_LIST_BEGIN && c != OP_LIST_END) n++;
        }
        return n;
    }

    /**
     * The wire program for one command in one direction, or null when the id
     * has no modelled layout in that direction.
     */
    public static String program(int cmd, boolean outbound) {
        ensure();
        return programs.get(key(cmd, outbound));
    }

    /**
     * Per-slot field names, indexed by program slot; entries are null where the
     * field name is still obfuscated. Null when the command has no layout or no
     * named field. <b>Do not mutate the returned array.</b>
     */
    public static String[] names(int cmd, boolean outbound) {
        ensure();
        return fieldNames.get(key(cmd, outbound));
    }

    /** The name of one slot, or null. */
    public static String nameOf(int cmd, boolean outbound, int slot) {
        String[] a = names(cmd, outbound);
        return (a != null && slot >= 0 && slot < a.length) ? a[slot] : null;
    }
}
