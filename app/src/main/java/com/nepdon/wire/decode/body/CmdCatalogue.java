package com.nepdon.wire.decode.body;

/**
 * Every packet event the game defines — {@value #COUNT} command ids, recovered
 * from the game's own metadata and cross-validated against the runtime handler
 * registry.
 *
 * <h3>Why this is a lookup table and not an enum</h3>
 *
 * <p>A Java {@code enum} with ~2000 constants generates its whole
 * {@code <clinit>} as bytecode and would sit right on the 64 KB method limit —
 * it might compile today and break on the next addition. String constants live
 * in the constant pool instead, so the data below costs nothing at class-init
 * and parses once, lazily, on first use.</p>
 *
 * <p>{@link Cmd} remains the enum for the ~60 ids the app actually acts on: it
 * is switchable, carries behaviour predicates, and is the right thing on a hot
 * path. <b>This class is the complete reference</b> — use it for logging,
 * capture annotation, the dev panel, and any "what is id 1709?" question.</p>
 *
 * <h3>Provenance</h3>
 *
 * <p>Two independently derived sources agree with <b>zero name disagreements</b>
 * over all 1384 ids they share:</p>
 * <ul>
 *   <li>the {@code message.KLINFKFBIKB} enum decoded from
 *       {@code global-metadata.dat} (names and values), and</li>
 *   <li>the runtime handler registry recovered by scanning every
 *       {@code NetworkClient.RegisterHandler<T>} call site (which ids the client
 *       can actually <i>receive</i>).</li>
 * </ul>
 *
 * <p>That agreement is what licenses trusting either one. See
 * {@code docs/IL2CPP_FINDINGS.md} and {@code tools/il2cpp/}.</p>
 *
 * <p><b>Generated file — do not hand-edit.</b> Regenerate from
 * {@code tools/ff_cmd_catalogue.txt} + {@code tools/il2cpp/ff_inbound_registry.tsv}.</p>
 */
public final class CmdCatalogue {
    /** Total command ids known. */
    public static final int COUNT = 1974;
    /** Ids with a registered inbound handler, i.e. the client can receive them. */
    public static final int INBOUND_COUNT = 1384;

    // The name table (Bucket-B) is provided per build variant by
    // CmdCatalogueData.PACKED — full in debug, EMPTY in release where it
    // is delivered from the server into RAM at login (see loadServerNames
    // and docs/SECURITY_MODEL.md). GENERATED by tools/offload_cmd_catalogue.py.

    private static volatile java.util.HashMap<Integer, String> names;
    private static volatile java.util.HashSet<Integer> inboundIds;

    /**
     * Server-delivered name table (Bucket-B, docs/SECURITY_MODEL.md). When the
     * login flow loads the config blob it calls {@link #loadServerNames}, and
     * these take precedence over the {@code CmdCatalogueData.PACKED} fallback.
     * That fallback is FULL in debug and EMPTY in release, so the release APK
     * ships without the table and relies on this server-delivered copy.
     */
    private static volatile java.util.HashMap<Integer, String> serverNames;

    private CmdCatalogue() { }

    /** Install the server-delivered id→name table (RAM only; never persisted). */
    public static void loadServerNames(java.util.Map<Integer, String> m) {
        if (m == null || m.isEmpty()) return;
        serverNames = new java.util.HashMap<>(m);
    }

    /** True once the server table has been installed this session. */
    public static boolean hasServerNames() {
        return serverNames != null;
    }

    /**
     * Drop the server-delivered table. Called from {@link
     * com.nepdon.wire.auth.ConfigStore#clear()} on logout / background
     * timeout so the crown-jewel knowledge does not stay resident for the whole
     * process lifetime. Clears entries before releasing the map so a lingering
     * reference cannot still read them.
     */
    public static void clearServerNames() {
        java.util.HashMap<Integer, String> sn = serverNames;
        serverNames = null;
        if (sn != null) sn.clear();
    }

    private static void ensure() {
        if (names != null) return;
        synchronized (CmdCatalogue.class) {
            if (names != null) return;
            java.util.HashMap<Integer, String> n = new java.util.HashMap<>(COUNT * 2);
            java.util.HashSet<Integer> in = new java.util.HashSet<>(INBOUND_COUNT * 2);
            for (String chunk : CmdCatalogueData.PACKED) {
                int i = 0, len = chunk.length();
                while (i < len) {
                    int end = chunk.indexOf('|', i);
                    if (end < 0) end = len;
                    boolean isIn = chunk.charAt(i) == '<';
                    int s = isIn ? i + 1 : i;
                    int colon = chunk.indexOf(':', s);
                    if (colon > 0 && colon < end) {
                        int id = 0;
                        for (int k = s; k < colon; k++) id = id * 10 + (chunk.charAt(k) - '0');
                        n.put(id, chunk.substring(colon + 1, end));
                        if (isIn) in.add(id);
                    }
                    i = end + 1;
                }
            }
            inboundIds = in;
            names = n;   // published last: ensure() keys off this
        }
    }

    /** The game's own name for a command id, or null if unknown. */
    public static String name(int cmd) {
        java.util.HashMap<Integer, String> sn = serverNames;
        if (sn != null) {
            String s = sn.get(cmd);
            if (s != null) return s;
        }
        ensure();
        return names.get(cmd);
    }

    /** The game's own name, or a readable fallback for unknown ids. */
    public static String nameOr(int cmd) {
        String s = name(cmd);
        return s != null ? s : ("CMD_" + cmd);
    }

    /**
     * True for the reserved transport range (1..99): hello, ack, ping, byebye,
     * the idle probe and datagram fragments. <b>Never withhold these</b> —
     * starving them trips the client's disconnect flags.
     */
    public static boolean isTransport(int cmd) {
        return cmd >= 1 && cmd <= 99;
    }

    /** "1709 RUDP_C2S_CARRY_BATTLE_HIT" — for logs and the dev panel. */
    public static String describe(int cmd) {
        return cmd + " " + nameOr(cmd);
    }

}
